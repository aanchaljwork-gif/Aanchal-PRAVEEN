// Web Audio API Sound Synthesizer (Works 100% offline, zero audio assets needed)

let audioCtx: AudioContext | null = null;
let soundEnabled = true;

function getAudioContext(): AudioContext | null {
  if (typeof window === 'undefined') return null;
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

export const toggleSound = (enabled?: boolean): boolean => {
  if (typeof enabled === 'boolean') {
    soundEnabled = enabled;
  } else {
    soundEnabled = !soundEnabled;
  }
  try {
    localStorage.setItem('odyssey_sound_enabled', soundEnabled ? 'true' : 'false');
  } catch (e) {
    // Ignore localStorage errors
  }
  return soundEnabled;
};

export const isSoundEnabled = (): boolean => {
  try {
    const stored = localStorage.getItem('odyssey_sound_enabled');
    if (stored !== null) return stored === 'true';
  } catch (e) {
    // Ignore
  }
  return soundEnabled;
};

// Play a short mechanical click
export const playClick = () => {
  if (!soundEnabled) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'sine';
    osc.frequency.setValueAtTime(800, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(300, ctx.currentTime + 0.04);
    gain.gain.setValueAtTime(0.08, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.04);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start();
    osc.stop(ctx.currentTime + 0.04);
  } catch (e) {
    // Audio context may be blocked by browser policy until interaction
  }
};

